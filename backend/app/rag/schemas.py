class SourceVerificationStatus(str, Enum):
    VERIFIED = "verified"
    NEEDS_REVIEW = "needs_review"
    OUTDATED = "outdated"
    RETIRED = "retired"
    SOURCE_METADATA_CONFLICT = "source_metadata_conflict"
    UNVERIFIED = "unverified"
    PROVISIONAL = "provisional"
    REVOKED = "revoked"

class DocumentProvenance(str, Enum):
    OFFICIAL_ORIGINAL = "OFFICIAL_ORIGINAL"                # Genuine authentic binary from issuing authority
    OFFICIAL_COPY = "OFFICIAL_COPY"                        # Certified official duplicate from authentic government source
    GOVERNMENT_REFERENCE = "GOVERNMENT_REFERENCE"          # Authoritative reference circular / advisory / matrix issued by government
    HISTORICAL_REFERENCE = "HISTORICAL_REFERENCE"          # Historical superseded circular / document for lineage/audit only
    APPLICATION_GENERATED = "APPLICATION_GENERATED"        # Synthesized/reconstructed form template generated by CONVELINA
    SYNTHETIC_DEVELOPMENT_SAMPLE = "SYNTHETIC_DEVELOPMENT_SAMPLE" # Synthetic test asset for local development & testing
    SYNTHETIC_TEST_ASSET = "SYNTHETIC_TEST_ASSET"          # Backward compatibility alias
    UNVERIFIED_SOURCE = "UNVERIFIED_SOURCE"                # Unverified provenance asset or external draft
    UNVERIFIED = "UNVERIFIED"                              # Backward compatibility alias

class UpdateVerificationStatusRequest(BaseModel):
    verification_status: SourceVerificationStatus
    review_notes: Optional[str] = None

